// The view schema the kit validates with: the frame's own schema (kit/host/views/plugin-view.schema.json, vendored
// verbatim) plus a few rules the frame's validator (PluginViewParser.kt) enforces that the upstream schema doesn't
// express yet. `node kit/src/schema.mjs --write` regenerates kit/schema/plugin-view.schema.json (sync-host.sh does).
// Each extension is a no-op once upstream has it, so a sync never breaks on it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { KIT_DIR } from './paths.mjs';
import { join } from 'node:path';

export const UPSTREAM = join(KIT_DIR, 'host', 'views', 'plugin-view.schema.json');
export const SCHEMA = join(KIT_DIR, 'schema', 'plugin-view.schema.json');

/** What the kit adds, for the record (also printed by `kit check --explain-schema`). */
export const EXTENSIONS = [
  'short strings: no C1 control characters (U+0080–U+009F) and not only whitespace (the frame: isISOControl, isBlank)',
  'sparkline: highlight_tone needs highlight (dependentRequired)',
  'sparkline points and flow edge power: magnitude at most 1e12 (ViewLimits.MAX_MAGNITUDE)',
];

export function buildSchema(upstream = JSON.parse(readFileSync(UPSTREAM, 'utf8'))) {
  const s = structuredClone(upstream);
  const d = s.$defs;
  const SHORT = '^(?=[\\s\\S]*\\S)[^\\u0000-\\u001f\\u007f-\\u009f\\u2028\\u2029]*$';
  if (d.short && d.short.pattern !== SHORT) d.short.pattern = SHORT;
  const sp = d.sparkline;
  if (sp && !sp.dependentRequired) sp.dependentRequired = { highlight_tone: ['highlight'] };
  const pts = sp && sp.properties.points && sp.properties.points.items;
  if (pts && pts.maximum === undefined) Object.assign(pts, { minimum: -1e12, maximum: 1e12 });
  const power = d.flow && d.flow.properties.edges.items.properties.power;
  if (power && power.maximum === undefined) power.maximum = 1e12;
  s.$comment = 'Generated by kit/src/schema.mjs from kinframe docs/api/plugin-views/plugin-view.schema.json (kit/host/SOURCE), with: ' + EXTENSIONS.join('; ') + '.';
  return s;
}

export const schemaText = () => JSON.stringify(buildSchema(), null, 2) + '\n';

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) writeFileSync(SCHEMA, schemaText());
  else process.stdout.write(schemaText());
}
